from sklearn.svm import LinearSVC
from sklearn.preprocessing import MultiLabelBinarizer
from sklearn.multiclass import OneVsRestClassifier
import re

# Function to parse tags string into a list of individual tags
def parse_tags(tags_string):
    if isinstance(tags_string, str):
        # Remove <> and split by >< to get individual tags
        return [tag.strip() for tag in re.findall(r'<(.*?)>', tags_string)]
    return []

# Function to filter parsed tags, keeping only frequent ones
def filter_to_frequent_tags(parsed_tag_list, frequent_tags_set):
    return [tag for tag in parsed_tag_list if tag in frequent_tags_set]

# Define frequent_tags using tag_df (e.g., top 1000 frequent tags)
# tag_df is available from a previous cell.
frequent_tags = tag_df["Tag"].head(1000).tolist() # Assuming top 1000 tags are considered frequent.

# Transform y_train and y_test into lists of all parsed tags
y_train_parsed = y_train.apply(parse_tags)
y_test_parsed = y_test.apply(parse_tags)

# Convert frequent_tags list (defined in the previous cell) to a set for faster lookup
frequent_tags_set = set(frequent_tags)

# Filter y_train_parsed and y_test_parsed to include only frequent tags
y_train_filtered = y_train_parsed.apply(lambda x: filter_to_frequent_tags(x, frequent_tags_set))
y_test_filtered = y_test_parsed.apply(lambda x: filter_to_frequent_tags(x, frequent_tags_set))

# Initialize MultiLabelBinarizer
mlb = MultiLabelBinarizer()
# Fit MLB only on the frequent tags to define its classes. This prevents warnings for very rare tags.
mlb.fit([frequent_tags])

y_train_multilabel = mlb.transform(y_train_filtered)
y_test_multilabel = mlb.transform(y_test_filtered)

# Train a OneVsRestClassifier with LinearSVC
model = OneVsRestClassifier(LinearSVC(class_weight="balanced", dual=False)) # Added dual=False for sparse data
model.fit(X_train_tfidf, y_train_multilabel)

from sklearn.metrics import f1_score, classification_report

y_pred_multilabel = model.predict(X_test_tfidf)

print("F1-score (micro):", f1_score(y_test_multilabel, y_pred_multilabel, average="micro"))
print("F1-score (macro):", f1_score(y_test_multilabel, y_pred_multilabel, average="macro"))
print("F1-score (weighted):", f1_score(y_test_multilabel, y_pred_multilabel, average="weighted"))

