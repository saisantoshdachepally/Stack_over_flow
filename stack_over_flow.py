def predict_tag(title, body):
    text = title + " " + body
    text_vec = vectorizer.transform([text])
    prediction_multilabel = model.predict(text_vec)
    # Convert multi-hot encoded prediction back to tag names
    predicted_tags = mlb.inverse_transform(prediction_multilabel)
    # inverse_transform returns a list of tuples, even for a single prediction
    # So we take the first element (which is a tuple of tags for the single input)
    return list(predicted_tags[0])

